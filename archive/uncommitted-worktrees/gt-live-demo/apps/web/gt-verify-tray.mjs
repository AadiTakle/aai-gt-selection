import { chromium } from '@playwright/test';
const b = await chromium.launch();
const p = await b.newPage({ viewport: { width: 1440, height: 900 } });
const errs = []; p.on('pageerror', (e) => errs.push(String(e)));
await p.goto('http://localhost:4100/dev/family-preview/exam?debug=1', { waitUntil: 'networkidle' });
await p.getByRole('button', { name: /Start the assessment/i }).click();
await p.waitForSelector('iframe', { timeout: 30000 });
console.log('QUESTION     :', (await p.locator('iframe').count()) > 0 ? 'renders' : 'MISSING');
const tray = p.locator('aside[aria-label="Debug: ability convergence"]');
const handle = tray.locator('button[aria-expanded]');
console.log('TRAY PRESENT :', (await tray.count()) > 0);
console.log('COLLAPSED H  :', Math.round((await tray.boundingBox())?.height ?? -1), 'px of 900 viewport');
console.log('HANDLE TEXT  :', (await handle.innerText()).replace(/\n/g, ' '));
await p.screenshot({ path: 'tray-collapsed.png' });
await p.getByRole('button', { name: /^Emulate/ }).first().click();
await p.waitForTimeout(600);
console.log('AFTER EMULATE:', (await handle.innerText()).replace(/\n/g, ' '));
await handle.click(); await p.waitForTimeout(400);
console.log('EXPANDED H   :', Math.round((await tray.boundingBox())?.height ?? -1), 'px; rows:', await tray.locator('tbody tr').count());
await p.screenshot({ path: 'tray-expanded.png' });
await handle.click(); await p.waitForTimeout(400);
console.log('RE-COLLAPSED :', Math.round((await tray.boundingBox())?.height ?? -1), 'px');
console.log('STATE KEPT   :', (await handle.innerText()).replace(/\n/g, ' '));
console.log('PAGE ERRORS  :', errs.length ? errs : 'none');
await b.close();
