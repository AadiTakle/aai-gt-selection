// --- seeded randomness --------------------------------------------------------

function xmur3(str: string): () => number {
  let h = 1779033703 ^ str.length;
  for (let i = 0; i < str.length; i += 1) {
    h = Math.imul(h ^ str.charCodeAt(i), 3432918353);
    h = (h << 13) | (h >>> 19);
  }
  return () => {
    h = Math.imul(h ^ (h >>> 16), 2246822507);
    h = Math.imul(h ^ (h >>> 13), 3266489909);
    h ^= h >>> 16;
    return h >>> 0;
  };
}

function mulberry32(a: number): () => number {
  let s = a;
  return () => {
    s |= 0;
    s = (s + 0x6d2b79f5) | 0;
    let t = Math.imul(s ^ (s >>> 15), 1 | s);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

/** Seeded uniform stream. Same xmur3 → mulberry32 idiom the bank generators use. */
function makeRng(seed: string): () => number {
  return mulberry32(xmur3(seed)());
}

/** Box–Muller normal draw from a uniform stream. */
function normal(rng: () => number, mean: number, sd: number): number {
  const u = Math.max(rng(), Number.EPSILON);
  const v = rng();
  return mean + sd * Math.sqrt(-2 * Math.log(u)) * Math.cos(2 * Math.PI * v);
}

function clamp(x: number, lo: number, hi: number): number {
  return Math.min(hi, Math.max(lo, x));
}

// --- statistics ---------------------------------------------------------------

function mean(xs: readonly number[]): number {
  return xs.length === 0 ? Number.NaN : xs.reduce((a, b) => a + b, 0) / xs.length;
}

function sd(xs: readonly number[]): number {
  if (xs.length < 2) return Number.NaN;
  const m = mean(xs);
  return Math.sqrt(xs.reduce((a, b) => a + (b - m) * (b - m), 0) / (xs.length - 1));
}

function pearson(xs: readonly number[], ys: readonly number[]): number {
  const n = Math.min(xs.length, ys.length);
  if (n < 2) return Number.NaN;
  const mx = mean(xs.slice(0, n));
  const my = mean(ys.slice(0, n));
  let sxy = 0;
  let sxx = 0;
  let syy = 0;
  for (let i = 0; i < n; i += 1) {
    const dx = (xs[i] ?? 0) - mx;
    const dy = (ys[i] ?? 0) - my;
    sxy += dx * dy;
    sxx += dx * dx;
    syy += dy * dy;
  }
  return sxx > 0 && syy > 0 ? sxy / Math.sqrt(sxx * syy) : Number.NaN;
}

/** OLS slope of `ys` on `xs` — the attenuation coefficient in the regression sense. */
function slopeOf(xs: readonly number[], ys: readonly number[]): number {
  const n = Math.min(xs.length, ys.length);
  if (n < 2) return Number.NaN;
  const mx = mean(xs.slice(0, n));
  const my = mean(ys.slice(0, n));
  let sxy = 0;
  let sxx = 0;
  for (let i = 0; i < n; i += 1) {
    const dx = (xs[i] ?? 0) - mx;
    sxy += dx * ((ys[i] ?? 0) - my);
    sxx += dx * dx;
  }
  return sxx > 0 ? sxy / sxx : Number.NaN;
}

/** Monte-Carlo standard error of a mean, which is what "≈ 0 within error" has to be judged against. */
function seOfMean(xs: readonly number[]): number {
  return sd(xs) / Math.sqrt(xs.length);
}

// --- item pools ---------------------------------------------------------------

function repoRoot(): string {
  let dir = dirname(fileURLToPath(import.meta.url));
  for (let depth = 0; depth < 10; depth += 1) {
    if (existsSync(join(dir, 'pnpm-workspace.yaml'))) return dir;
    const parent = resolve(dir, '..');
    if (parent === dir) break;
    dir = parent;
  }
  throw new Error('learning-block harness: could not locate the workspace root');
}

const BANK_DIR = join(repoRoot(), 'research/exam-question-types/banks');

/**
 * Where a scrambled-control arm lives.
 *
 * `banks/` is the directory the app serves from, so the `perTrial` arm is deliberately not in it
 * (see the header of `generators/FLU-OPCHAIN-01.mjs`). Gate A still has to run BOTH arms through
 * this one driver — §4.1.1 requires the same driver, or the contrast is confounded with it — so the
 * harness names the control directory explicitly. This is research tooling: it never runs in the
 * app, and reaching a bank from here serves nothing to anybody.
 */
const CONTROL_BANK_DIR = join(repoRoot(), 'research/exam-question-types/control-banks');

function poolItem(itemId: string, typeCode: string, difficulty: number): BankItem {
  return {
    itemId,
    typeCode,
    domain: 'fluid_reasoning',
    difficulty,
    ageBands: ['4-5'] as AgeBand[],
    content: {},
    answer: { correctKey: 'A' },
    scoring: { mode: 'deterministic_key' },
    provenance: { generator: 'grammar' },
    syntheticOnly: true,
    validated: false,
  };
}

/**
 * An idealised pool on a fixed difficulty grid — E-095's "0.5-point item grid".
 *
 * This is the control condition for the harness itself: it isolates what the ESTIMATOR does from
 * what a particular bank's grid does to it. `perRung` has to exceed the block length divided by the
 * number of rungs the block visits, or the pool runs out and the comparison measures exhaustion.
 */
function gridPool(step: number, perRung: number): BankItem[] {
  const items: BankItem[] = [];
  for (let d = SCALE_MIN; d <= SCALE_MAX + 1e-9; d += step) {
    const difficulty = Math.round(d * 100) / 100;
    for (let i = 0; i < perRung; i += 1) {
      items.push(poolItem(`grid-${difficulty.toFixed(2)}-${i}`, 'GRID-IDEAL-01', difficulty));
    }
  }
  return items;
}

/** Resolve `--bank` as a path, a bank file stem, or a bare type code, in either bank directory. */
function resolveBankPath(ref: string): string {
  const candidates = [
    isAbsolute(ref) ? ref : resolve(process.cwd(), ref),
    join(BANK_DIR, ref),
    join(BANK_DIR, `${ref}.jsonl`),
    join(CONTROL_BANK_DIR, ref),
    join(CONTROL_BANK_DIR, `${ref}.jsonl`),
  ];
  for (const candidate of candidates) if (existsSync(candidate)) return candidate;
  const listing = (dir: string) =>
    existsSync(dir)
      ? readdirSync(dir)
          .filter((f) => f.endsWith('.jsonl'))
          .join(', ')
      : '(missing)';
  throw new Error(
    `no bank found for "${ref}".\n  banks/: ${listing(BANK_DIR)}\n  control-banks/: ${listing(CONTROL_BANK_DIR)}`,
  );
}

interface LoadedBank {
  label: string;
  path: string;
  items: BankItem[];
}

/**
 * The reference the harness uses when `--bank grid` is asked for: the idealised pool as a bank.
 *
 * Gate A takes a bank, and until now the bank-free control could only be reached through
 * `--calibrate`, which does not run the gate. That is the wrong way round for the question the gate
 * is for: A1 asks whether the PIPELINE manufactures a climb, and the only condition that settles
 * where a manufactured climb comes from is the one with no bank in it. `STAGE2_BANK_RECOVERY_MEASUREMENT`
 * §3.1 had to assemble that row by hand from a different code path; this makes it the same command.
 */
const GRID_BANK_REF = 'grid';

function loadBank(ref: string): LoadedBank {
  if (ref === GRID_BANK_REF) {
    return {
      label: 'ideal 0.5-point grid (no bank)',
      path: '(synthesised in-process — gridPool(0.5, 12))',
      items: gridPool(0.5, 12),
    };
  }
  const path = resolveBankPath(ref);
  const items: BankItem[] = [];
  for (const line of readFileSync(path, 'utf8').split('\n')) {
    const trimmed = line.trim();
    if (trimmed.length === 0) continue;
    const row = JSON.parse(trimmed) as Record<string, unknown>;
    const itemId = row['itemId'];
    const typeCode = row['typeCode'];
    const difficulty = row['difficulty'];
    if (typeof itemId !== 'string' || typeof typeCode !== 'string') continue;
    if (typeof difficulty !== 'number' || !Number.isFinite(difficulty)) continue;
    items.push(poolItem(itemId, typeCode, difficulty));
  }
  if (items.length === 0) throw new Error(`bank ${path} yielded no usable items`);
  return { label: ref, path, items };
}

/**
 * Which bank file an arm reads, given a `--bank` reference and a `--mode`.
 *
 * A dual-mode pair is the bare `<CODE>.jsonl` in `banks/` (the consistent arm, which is the one the
 * app serves) plus `<CODE>.perTrial.jsonl` in `control-banks/`. A reference naming either arm, or
 * naming neither, resolves to the requested one; a single-arm bank ignores the mode.
 */
function bankRefForMode(ref: string, mode: Persistence): string {
  if (ref === GRID_BANK_REF) return ref;
  const stem = ref.replace(/\.jsonl$/, '').replace(/\.(consistent|perTrial)$/, '');
  if (mode === 'perTrial') {
    const control = `${stem}.perTrial`;
    return existsSync(join(CONTROL_BANK_DIR, `${control}.jsonl`)) ? control : ref;
  }
  return existsSync(join(BANK_DIR, `${stem}.jsonl`)) ? stem : ref;
}

// --- one block ----------------------------------------------------------------

type Persistence = 'consistent' | 'perTrial';

interface ChildSpec {
  /** Ability at trial 0, on the [1, 20] scale. */
  theta0: number;
  /** True climb in scale points per trial. */
  lambda: number;
  /**
   * The settled standing estimate handed over from Phase 1. Deliberately NOT equal to `theta0`:
   * §4.4 of the design doc names regression to the mean at the handover as a source of spurious λ,
   * and E-095's sweep included the same noise, so a harness without it would flatter the estimator.
   */
  standing: number;
  seed: string;
}

interface BlockRun {
  trials: LearningTrial[];
  served: { difficulty: number; target: number; correct: boolean }[];
  /** True when the pool ran out before the requested length — reportable, never silent. */
  exhausted: boolean;
}

interface Responder {
  slope: number;
  /** Lower asymptote of the response curve. The item's real pseudo-guessing floor, not the fit's. */
  guessing: number;
}

/**
 * What the ESTIMATOR assumes, held separately from what the child actually does.
 *
 * Two floors rather than one because the block runs the estimator twice per trial in two different
 * roles, and they can be corrected independently. `readout` is the floor the reported fit uses;
 * `targeting` is the floor `nextTargetTheta` uses when it re-fits to choose the next difficulty.
 * Correcting only the first leaves the difficulty walk itself still driven by a misspecified fit,
 * and the walk is half the mechanism — so an arm that changes one and not the other is a distinct,
 * measurable remedy rather than a variation on the same one.
 */
interface FitSpec {
  readonly readout: number;
  readonly targeting: number;
}

/**
 * Which rule chooses the difficulty of the next trial. `level` is what ships.
 *
 * The other three are diagnostics, not administration options, and they exist because the
 * differences between them are the whole of D-206:
 *
 * - `projecting` is the rule the block shipped with before D-206 — aim at `theta0 + lambda * t`,
 *   the ability PROJECTED for the next trial. It closes a loop from the estimate of `lambda` back
 *   onto the design that identifies `lambda`. Kept so the before/after can be run at matched seeds
 *   in one version of this harness; a comparison across two harness versions would be confounded
 *   with the harness.
 * - `level-plain` is D-206 as first drafted: the level fit plus the offset, with no accuracy
 *   correction on top. It removes the loop but lags a climbing child, and the size of that lag is
 *   what the correction in `level` was added to fix. Kept so the correction's cost is measurable
 *   against the thing it was added to rather than against the rule two revisions back.
 * - `frozen` holds the difficulty at `standing + offset` for the whole block. It is the open-loop
 *   bound: the block still uses the real fit, but nothing the fit says reaches what gets served. It
 *   is the only way to separate what the ESTIMATOR does from what the LOOP does.
 */
type TargetingRule = 'level' | 'level-plain' | 'projecting' | 'frozen';

/** The rule D-206 replaced, kept here rather than in the estimator so the shipped path has one. */
function projectingTargetTheta(
  trials: readonly LearningTrial[],
  standing: number,
  fitGuessing: number,
): number {
  if (trials.length < MIN_TRIALS_FOR_PROJECTION) {
    return clamp(standing + TARGET_OFFSET, SCALE_MIN, SCALE_MAX);
  }
  const fit = estimateLearningCurve(trials, {
    slope: SLOPE,
    priorTheta0Mean: standing,
    guessing: fitGuessing,
  });
  return clamp(fit.theta0 + fit.lambda * trials.length + TARGET_OFFSET, SCALE_MIN, SCALE_MAX);
}

/**
 * Administer one novel block, using the shipped administration path end to end.
 *
 * The engine picks the item (`selectNextNovelItem`), the scorer picks the difficulty to aim at
 * (`nextTargetTheta`), and the simulated child answers under a 1PL with an explicit guessing floor.
 * Nothing about the block is pre-scripted: the difficulty walk is whatever the targeting rule and
 * the bank's grid produce together, which is the only reason the run says anything about the bank.
 */
function runBlock(
  pool: readonly BankItem[],
  child: ChildSpec,
  length: number,
  responder: Responder,
  fit: FitSpec,
  targeting: TargetingRule,
  selectionSeed: number,
): BlockRun {
  const rng = makeRng(`response|${child.seed}`);
  const trials: LearningTrial[] = [];
  const served: BlockRun['served'] = [];
  const administered: string[] = [];
  let exhausted = false;

  for (let t = 0; t < length; t += 1) {
    let target: number;
    if (targeting === 'frozen') {
      target = clamp(child.standing + TARGET_OFFSET, SCALE_MIN, SCALE_MAX);
    } else if (targeting === 'projecting') {
      target = projectingTargetTheta(trials, child.standing, fit.targeting);
    } else if (targeting === 'level-plain') {
      target =
        trials.length < MIN_TRIALS_FOR_PROJECTION
          ? clamp(child.standing + TARGET_OFFSET, SCALE_MIN, SCALE_MAX)
          : clamp(
              estimateBlockLevel(trials, {
                slope: SLOPE,
                priorTheta0Mean: child.standing,
                guessing: fit.targeting,
              }) + TARGET_OFFSET,
              SCALE_MIN,
              SCALE_MAX,
            );
    } else {
      target = nextTargetTheta(trials, {
        standingEstimate: child.standing,
        targetOffset: TARGET_OFFSET,
        slope: responder.slope,
        guessing: fit.targeting,
      });
    }
    const item = selectNextNovelItem(pool, administered, target, selectionSeed);
    if (item === null) {
      exhausted = true;
      break;
    }
    administered.push(item.itemId);

    const ability = child.theta0 + child.lambda * t;
    const star = 1 / (1 + Math.exp(-responder.slope * (ability - item.difficulty)));
    const p = responder.guessing + (1 - responder.guessing) * star;
    const correct = rng() < p;

    trials.push({ difficulty: item.difficulty, score: correct ? 1 : 0, trialIndex: t });
    served.push({ difficulty: item.difficulty, target, correct });
  }

  return { trials, served, exhausted };
}

// --- a cohort -----------------------------------------------------------------

interface CohortOptions {
  pool: readonly BankItem[];
  children: number;
  length: number;
  lambdaMean: number;
  lambdaSd: number;
  /** SD of the noise on the standing handover, in scale points. */
  standingNoise: number;
  theta0Mean: number;
  theta0Sd: number;
  responder: Responder;
  fit: FitSpec;
  /** Which rule chooses the next difficulty. Defaults to the shipped one. See {@link TargetingRule}. */
  targeting?: TargetingRule;
  /**
   * Contamination floor to declare on `A2_REFERENCE` for the third readout pass, which is how the
   * cost of the evidence bar gets measured. Supplied from the matching λ_true = 0 run, so the bar is
   * always the floor this arm actually manufactures rather than a figure chosen to look good.
   */
  barFloor?: number;
  seed: number;
}

interface CohortResult {
  n: number;
  length: number;
  trueLambda: number[];
  fitLambda: number[];
  fitLambdaSe: number[];
  /** Mean served difficulty over the final third — §4.1.1's manipulation check observable. */
  lateDifficulty: number[];
  /** Highest difficulty served to each child, for the saturation check (A3). */
  peakDifficulty: number[];
  /** Highest difficulty each child's targeting rule ASKED for, before the pool had its say. */
  peakDemand: number[];
  /** Fraction of children whose readout came back `above` against a separable reference. */
  aboveRate: number;
  /**
   * Fraction whose readout declined to name a band at all, against the same separable reference.
   *
   * The cost side of every remedy below. A fix that restores λ̄ = 0 by widening the posterior until
   * nothing is reportable has not made the measurement honest, it has removed it, and only this
   * column distinguishes the two.
   */
  indeterminateRate: number;
  /** Same, against {@link NARROW_REFERENCE} — the reportability question rather than the band. */
  narrowIndeterminateRate: number;
  /** Same, against the SD 0.15 reference WITH this arm's own contamination floor declared. */
  barIndeterminateRate: number;
  exhaustedCount: number;
  poolMax: number;
  shortBlocks: number;
}

/**
 * A separable reference, used ONLY to count false `above` verdicts for Gate A's A2.
 *
 * Deliberately not an honest reference: at 30 trials an honest narrow reference returns
 * `indeterminate` for everybody (E-095), which would make A2 vacuously pass. `sd: 0.15` is the
 * smallest spread at which the bands separate at this length, which is the same device
 * `exam-phase2-demo.ts` calls its "wide reference" and flags as not a claim about children.
 *
 * `contaminationFloor: 0` is not a claim that there is no contamination — E-200 measures plenty. It
 * is what makes A2 a measurement of the pipeline's false-`above` rate rather than a measurement of
 * the bar: with the floor declared, the readout would refuse to name any band at this length and A2
 * would pass on every bank ever built. The `--fix-probe` table reports the bar's cost separately.
 */
const A2_REFERENCE = { mean: 0, sd: 0.15, contaminationFloor: 0 } as const;

/**
 * The reference the project's own synthetic work actually used: centre 0.06, SD 0.03.
 *
 * Carried alongside `A2_REFERENCE` so every remedy is costed against BOTH the widest reference
 * anyone has proposed and the only one with a stated provenance. The two answer different questions.
 * Against `A2_REFERENCE` a remedy can be judged on how often it names a band; against this one the
 * answer is expected to be "never", and a remedy that changed that would be the surprise.
 */
const NARROW_REFERENCE = { mean: 0.06, sd: 0.03, contaminationFloor: 0 } as const;

function runCohort(options: CohortOptions): CohortResult {
  const {
    pool,
    children,
    length,
    lambdaMean,
    lambdaSd,
    standingNoise,
    theta0Mean,
    theta0Sd,
    responder,
    fit: fitSpec,
    targeting = 'level',
    barFloor = 0,
    seed,
  } = options;

  const rng = makeRng(`cohort|${seed}|${length}|${lambdaMean}|${lambdaSd}|${standingNoise}`);
  const trueLambda: number[] = [];
  const fitLambda: number[] = [];
  const fitLambdaSe: number[] = [];
  const lateDifficulty: number[] = [];
  const peakDifficulty: number[] = [];
  const peakDemand: number[] = [];
  let aboveCount = 0;
  let indeterminateCount = 0;
  let narrowIndeterminateCount = 0;
  let barIndeterminateCount = 0;
  let exhaustedCount = 0;
  let shortBlocks = 0;

  for (let c = 0; c < children; c += 1) {
    const theta0 = clamp(normal(rng, theta0Mean, theta0Sd), SCALE_MIN, SCALE_MAX);
    const lambda = lambdaSd > 0 ? normal(rng, lambdaMean, lambdaSd) : lambdaMean;
    const standing = clamp(theta0 + normal(rng, 0, standingNoise), SCALE_MIN, SCALE_MAX);
    const child: ChildSpec = { theta0, lambda, standing, seed: `${seed}|${length}|${c}` };

    const run = runBlock(pool, child, length, responder, fitSpec, targeting, seed);
    if (run.exhausted) exhaustedCount += 1;
    if (run.trials.length < length) shortBlocks += 1;
    if (run.trials.length === 0) continue;

    const fit = estimateLearningCurve(run.trials, {
      slope: responder.slope,
      priorTheta0Mean: child.standing,
      guessing: fitSpec.readout,
    });
    trueLambda.push(lambda);
    fitLambda.push(fit.lambda);
    fitLambdaSe.push(fit.lambdaSe);

    const cut = Math.floor((2 * run.served.length) / 3);
    lateDifficulty.push(mean(run.served.slice(cut).map((s) => s.difficulty)));
    peakDifficulty.push(Math.max(...run.served.map((s) => s.difficulty)));
    peakDemand.push(Math.max(...run.served.map((s) => s.target)));

    const readout = learningRateReadout(run.trials, {
      reference: A2_REFERENCE,
      minTrials: length,
      fit: { slope: responder.slope, guessing: fitSpec.readout },
    });
    if (readout.band === 'above') aboveCount += 1;
    if (readout.band === 'indeterminate') indeterminateCount += 1;

    const narrow = learningRateReadout(run.trials, {
      reference: NARROW_REFERENCE,
      minTrials: length,
      fit: { slope: responder.slope, guessing: fitSpec.readout },
    });
    if (narrow.band === 'indeterminate') narrowIndeterminateCount += 1;

    const barred = learningRateReadout(run.trials, {
      reference: { ...A2_REFERENCE, contaminationFloor: barFloor },
      minTrials: length,
      fit: { slope: responder.slope, guessing: fitSpec.readout },
    });
    if (barred.band === 'indeterminate') barIndeterminateCount += 1;
  }

  return {
    n: fitLambda.length,
    length,
    trueLambda,
    fitLambda,
    fitLambdaSe,
    lateDifficulty,
    peakDifficulty,
    peakDemand,
    aboveRate: fitLambda.length === 0 ? Number.NaN : aboveCount / fitLambda.length,
    indeterminateRate: fitLambda.length === 0 ? Number.NaN : indeterminateCount / fitLambda.length,
    narrowIndeterminateRate:
      fitLambda.length === 0 ? Number.NaN : narrowIndeterminateCount / fitLambda.length,
    barIndeterminateRate:
      fitLambda.length === 0 ? Number.NaN : barIndeterminateCount / fitLambda.length,
    exhaustedCount,
    poolMax: Math.max(...pool.map((i) => i.difficulty)),
    shortBlocks,
  };
}

// --- reporting ----------------------------------------------------------------

function f(x: number, places = 3): string {
  return Number.isFinite(x) ? x.toFixed(places) : 'n/a';
}

function recoveryRow(result: CohortResult): {
  length: number;
  r: number;
  meanSe: number;
  attenuationRatio: number;
  attenuationSlope: number;
  fitLambdaSd: number;
} {
  const trueMean = mean(result.trueLambda);
  return {
    length: result.length,
    r: pearson(result.trueLambda, result.fitLambda),
    meanSe: mean(result.fitLambdaSe),
    // Two readings of "attenuation", because E-095 quotes one number ("fit/true") and does not say
    // which. They diverge when the prior shrinks the spread differently from the mean, and a
    // reproduction that reported only the agreeing one would be choosing its own evidence.
    attenuationRatio: trueMean === 0 ? Number.NaN : mean(result.fitLambda) / trueMean,
    attenuationSlope: slopeOf(result.trueLambda, result.fitLambda),
    fitLambdaSd: sd(result.fitLambda),
  };
}

interface Settings {
  children: number;
  length: number;
  lambdaMean: number;
  lambdaSd: number;
  standingNoise: number;
  theta0Mean: number;
  theta0Sd: number;
  guessing: number;
  /**
   * Whether `--guessing` was supplied. `--fix-probe` needs a responder that actually has a floor,
   * or every arm is comparing corrections against a truth of zero; it defaults its own responder to
   * the five-option floor, and this is how it tells "not supplied" from an explicit `--guessing 0`.
   */
  guessingExplicit: boolean;
  fitGuessing: number;
  targetGuessing: number;
  /** Which rule chooses the next difficulty. Diagnostic; `level` is what the block administers. */
  targeting: TargetingRule;
  seed: number;
  /**
   * Every seed Gate A should be run at. One cell of 400 children carries about ±0.04 of noise on
   * `r` and ±0.0033 on the null-cohort λ̄ (`STAGE2_BANK_RECOVERY_MEASUREMENT` §9), which is wider
   * than several differences worth reporting, so a single-seed Gate A cannot settle whether A1
   * passes. Supplying more than one prints a replication block alongside the per-seed reports.
   */
  seeds: number[];
  bank: string | null;
  mode: Persistence;
  json: boolean;
  calibrate: boolean;
  gateA: boolean;
  noiseSweep: boolean;
  guessingProbe: boolean;
  fixProbe: boolean;
}

function parseArgs(argv: readonly string[]): Settings {
  const flag = (name: string): string | null => {
    const index = argv.indexOf(`--${name}`);
    return index >= 0 ? (argv[index + 1] ?? null) : null;
  };
  const num = (name: string, fallback: number): number => {
    const raw = flag(name);
    if (raw === null) return fallback;
    const parsed = Number(raw);
    if (!Number.isFinite(parsed)) throw new Error(`--${name} expects a number, got "${raw}"`);
    return parsed;
  };
  const modeRaw = flag('mode') ?? 'consistent';
  if (modeRaw !== 'consistent' && modeRaw !== 'perTrial') {
    throw new Error(`--mode expects consistent|perTrial, got "${modeRaw}"`);
  }
  const targetingRules: readonly TargetingRule[] = ['level', 'level-plain', 'projecting', 'frozen'];
  const targetingRaw = flag('targeting') ?? 'level';
  if (!targetingRules.includes(targetingRaw as TargetingRule)) {
    throw new Error(`--targeting expects ${targetingRules.join('|')}, got "${targetingRaw}"`);
  }
  const seed = num('seed', 20260730);
  const seedsRaw = flag('seeds');
  const seeds =
    seedsRaw === null
      ? [seed]
      : seedsRaw.split(',').map((part) => {
          const parsed = Number(part.trim());
          if (!Number.isFinite(parsed)) throw new Error(`--seeds expects numbers, got "${part}"`);
          return parsed;
        });

  return {
    children: num('children', 400),
    length: num('length', RECOMMENDED_NOVEL_BLOCK_LENGTH),
    lambdaMean: num('lambda-mean', 0.06),
    lambdaSd: num('lambda-sd', 0.03),
    // 1.5 scale points, the `stabilitySd` the engine calls a settled estimate. E-095 says only
    // "deliberately noisy"; this is the repo's own figure for how noisy "settled" is.
    standingNoise: num('standing-noise', 1.5),
    theta0Mean: num('theta0-mean', 10.5),
    theta0Sd: num('theta0-sd', 3),
    guessing: num('guessing', 0),
    guessingExplicit: argv.includes('--guessing'),
    fitGuessing: num('fit-guessing', DEFAULT_GUESSING),
    targetGuessing: num('target-guessing', DEFAULT_GUESSING),
    targeting: targetingRaw as TargetingRule,
    seed,
    seeds,
    bank: flag('bank'),
    mode: modeRaw,
    json: argv.includes('--json'),
    calibrate: argv.includes('--calibrate'),
    gateA: argv.includes('--gate-a'),
    noiseSweep: argv.includes('--noise-sweep'),
    guessingProbe: argv.includes('--guessing-probe'),
    fixProbe: argv.includes('--fix-probe'),
  };
}

