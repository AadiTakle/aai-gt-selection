// --- calibration: does the harness reproduce E-095? ---------------------------

interface CalibrationRow {
  pool: string;
  length: number;
  r: number;
  meanSe: number;
  attenuationRatio: number;
  attenuationSlope: number;
  publishedR: number;
  publishedSe: number;
  publishedAttenuation: number;
}

function calibrate(settings: Settings): { rows: CalibrationRow[]; verdict: string[] } {
  const pools: { label: string; items: BankItem[] }[] = [
    { label: 'ideal 0.5-point grid', items: gridPool(0.5, 12) },
    { label: `bank ${REFERENCE_BANK}`, items: loadBank(REFERENCE_BANK).items },
  ];

  const rows: CalibrationRow[] = [];
  for (const pool of pools) {
    for (const length of LENGTH_LADDER) {
      const result = runCohort(cohortOptionsFor(settings, pool.items, { length }));
      const row = recoveryRow(result);
      const published = E095[length];
      rows.push({
        pool: pool.label,
        length,
        r: row.r,
        meanSe: row.meanSe,
        attenuationRatio: row.attenuationRatio,
        attenuationSlope: row.attenuationSlope,
        publishedR: published.r,
        publishedSe: published.meanSe,
        publishedAttenuation: published.attenuation,
      });
    }
  }

  const verdict: string[] = [];
  for (const row of rows.filter((r) => r.length === 30)) {
    const dR = Math.abs(row.r - row.publishedR);
    const dSe = Math.abs(row.meanSe - row.publishedSe);
    const dAtt = Math.min(
      Math.abs(row.attenuationRatio - row.publishedAttenuation),
      Math.abs(row.attenuationSlope - row.publishedAttenuation),
    );
    const ok =
      dR <= E095_TOLERANCE.r && dSe <= E095_TOLERANCE.meanSe && dAtt <= E095_TOLERANCE.attenuation;
    verdict.push(
      `${ok ? 'MATCH' : 'DIVERGES'}  ${row.pool} at 30 trials: ` +
        `|Δr| ${f(dR)} (tol ${E095_TOLERANCE.r}), |ΔSE| ${f(dSe)} (tol ${E095_TOLERANCE.meanSe}), ` +
        `|Δattenuation| ${f(dAtt)} (tol ${E095_TOLERANCE.attenuation})`,
    );
  }
  return { rows, verdict };
}

// --- Gate A -------------------------------------------------------------------

interface GateACheck {
  id: 'A1' | 'A2' | 'A3' | 'A4';
  name: string;
  pass: boolean;
  observed: string;
  condition: string;
  meaningOfFailure: string;
}

interface GateAReport {
  bank: string;
  path: string;
  mode: Persistence;
  items: number;
  difficultySpan: [number, number];
  distinctRungs: number;
  guessing: number;
  checks: GateACheck[];
  /** Fitted-λ SD on this bank, which U1's power script needs instead of the doc's 0.06 estimate. */
  fitLambdaSd: number;
  recovery: ReturnType<typeof recoveryRow>;
  nullMean: number;
  nullSe: number;
}

/**
 * Gate A (§4.1.2) on one bank in one mode.
 *
 * A1 is the check that earns its keep: a cohort with no learning at all must fit λ̄ = 0. A2 asks
 * whether the readout would call those non-learners fast. A3 asks whether the pool has the headroom
 * §1.1(c) requires. A4 asks whether the bank's grid supports the estimator at all, and also MEASURES
 * the fitted-λ SD the Gate B power calculation depends on.
 */
function gateA(settings: Settings, bank: LoadedBank, mode: Persistence): GateAReport {
  const pool = bank.items;

  // A1 / A2 — a cohort with λ_true = 0 for every child. No spread, so any fitted spread is the
  // pipeline's own.
  const nullCohort = runCohort(
    cohortOptionsFor(settings, pool, { lambdaMean: 0, lambdaSd: 0, length: settings.length }),
  );
  const nullMean = mean(nullCohort.fitLambda);
  const nullSe = seOfMean(nullCohort.fitLambda);
  const a1Pass = Math.abs(nullMean) <= 2 * nullSe;

  // The nominal rate is the tail mass beyond the band edge under the reference used, which for a
  // half-width of 0.5 SD is ~0.309 in a normal. A pipeline that manufactures nothing should sit
  // well under it; this asks only that it does not EXCEED it.
  const nominalAboveRate = 0.309;
  const a2Pass = nullCohort.aboveRate <= nominalAboveRate;

  // A3 — the fastest learner the design contemplates must not pin to the top of the pool.
  //
  // Split into two causes, because §4.1.2 states A3 as one check and it is two. A child pins at the
  // pool maximum either because the BANK stops below what the targeting rule asked for — which is
  // the §1.1(c) headroom defect A3 exists to catch and is fixable by generating deeper items — or
  // because the targeting rule asked for a difficulty ABOVE 20 and `nextTargetTheta` clamped it to
  // the scale. The second is a property of the [1, 20] scale, so no bank can fix it, and charging it
  // to the bank would make A3 unpassable for any cohort containing high-standing children. Only the
  // first is a failure. The second is reported as a stated boundary. See the deviation note below.
  const fastCohort = runCohort(
    cohortOptionsFor(settings, pool, {
      lambdaMean: 0.15,
      lambdaSd: 0,
      length: settings.length,
      children: Math.max(40, Math.floor(settings.children / 4)),
    }),
  );
  const poolMax = Math.max(...pool.map((i) => i.difficulty));
  let bankLimited = 0;
  let scaleLimited = 0;
  for (let i = 0; i < fastCohort.peakDifficulty.length; i += 1) {
    if ((fastCohort.peakDifficulty[i] ?? 0) < poolMax - 1e-9) continue;
    // The demand is clamped to SCALE_MAX by `nextTargetTheta`, so a child sitting AT the clamp is
    // one the scale cut off, not one the bank ran out on.
    if ((fastCohort.peakDemand[i] ?? 0) >= SCALE_MAX - 1e-9) scaleLimited += 1;
    else bankLimited += 1;
  }
  const a3Pass = bankLimited === 0 && fastCohort.exhaustedCount === 0;

  // A4 — recovery on this bank's actual grid, against E-095's 30-trial figures.
  const recoveryCohort = runCohort(cohortOptionsFor(settings, pool, { length: settings.length }));
  const recovery = recoveryRow(recoveryCohort);
  const published = settings.length === 30 ? E095[30] : null;
  const a4Pass =
    published !== null &&
    Math.abs(recovery.r - published.r) <= E095_TOLERANCE.r &&
    Math.abs(recovery.meanSe - published.meanSe) <= E095_TOLERANCE.meanSe;

  const difficulties = pool.map((i) => i.difficulty);
  const rungs = new Set(difficulties.map((d) => Math.round(d * 2) / 2));

  return {
    bank: bank.label,
    path: bank.path,
    mode,
    items: pool.length,
    difficultySpan: [Math.min(...difficulties), Math.max(...difficulties)],
    distinctRungs: rungs.size,
    guessing: settings.guessing,
    fitLambdaSd: recovery.fitLambdaSd,
    recovery,
    nullMean,
    nullSe,
    checks: [
      {
        id: 'A1',
        name: 'static-child null',
        pass: a1Pass,
        observed: `fitted λ̄ = ${f(nullMean, 4)} ± ${f(nullSe, 4)} (Monte-Carlo SE) over ${nullCohort.n} children`,
        condition: 'fitted λ distribution centred on 0 within Monte-Carlo error (|λ̄| ≤ 2 SE)',
        meaningOfFailure:
          'the ladder itself produces a climb — almost always trial-index-correlated difficulty ' +
          'misspecification (§1.1(d)), occasionally pool saturation',
      },
      {
        id: 'A2',
        name: 'false-positive rate',
        pass: a2Pass,
        observed: `${f(100 * nullCohort.aboveRate, 1)}% of static children read "above" (nominal ${f(100 * nominalAboveRate, 1)}%)`,
        condition: '`learningRateReadout` returns `above` no more often than the nominal band rate',
        meaningOfFailure: 'the readout would call non-learners fast learners',
      },
      {
        id: 'A3',
        name: 'no saturation',
        pass: a3Pass,
        observed:
          `fastest simulated learner (λ = 0.15), ${fastCohort.peakDifficulty.length} children: ` +
          `${bankLimited} pinned at the pool maximum ${f(poolMax, 2)} with the bank short of what was asked for; ` +
          `${scaleLimited} pinned because the projection hit the ${SCALE_MAX}-point scale ceiling (not a bank defect); ` +
          `${fastCohort.exhaustedCount} block(s) ran out of items`,
        condition:
          'no child is served the pool maximum while the targeting rule asked for more, and no block exhausts',
        meaningOfFailure:
          'headroom is short of §1.1(c), so the top of the λ distribution would be truncated',
      },
      {
        id: 'A4',
        name: 'recovery sanity',
        pass: a4Pass,
        observed:
          `r = ${f(recovery.r)} (E-095 ${f(published?.r ?? Number.NaN)}), ` +
          `mean SE = ${f(recovery.meanSe)} (E-095 ${f(published?.meanSe ?? Number.NaN)}), ` +
          `attenuation ratio ${f(recovery.attenuationRatio)} / slope ${f(recovery.attenuationSlope)}, ` +
          `fitted-λ SD = ${f(recovery.fitLambdaSd, 4)}`,
        condition: `recovery and mean SE within ±${E095_TOLERANCE.r} / ±${E095_TOLERANCE.meanSe} of E-095 at 30 trials`,
        meaningOfFailure:
          "the bank's grid is too coarse or too shallow to support the estimator at all",
      },
    ],
  };
}

