/**
 * U0 — the learning-block measurement harness (STAGE2_QUESTION_DESIGN §9.1).
 *
 * Drives a candidate item bank through the REAL administration path — `nextTargetTheta` +
 * `selectNextNovelItem` + `estimateLearningCurve` + `learningRateReadout` — for a simulated cohort,
 * in either `systemPersistence` mode, and reports what the bank's own difficulty grid does to the
 * estimator. It is the instrument Gate A (§4.1.2) is read off, and it is deliberately the first unit
 * built: a bank that cannot support the fit must be found before a renderer is written for it.
 *
 * WHAT THIS CAN AND CANNOT SHOW. Recovering an injected climb from responses generated by that same
 * climb is circular, and `learning-curve.ts` already says so. So the harness is NOT evidence that a
 * block measures learning. Its two honest uses are the converse:
 *
 *   1. **It does not manufacture λ.** Run a cohort with `λ_true = 0` — fixed ability, no learning
 *      whatsoever — through the real targeting rule on a real bank. The fitted λ̄ must come back at
 *      zero. When it does not, the bank's stated difficulties correlate with trial index and §1.1(d)
 *      of the design doc names the failure: structured labelling error maps straight onto `lambda`.
 *   2. **The bank's grid supports the estimator at all.** Recovery, attenuation and posterior SE on
 *      the bank's ACTUAL difficulty grid, compared against E-095's figures, which were measured on
 *      an idealised 0.5-point grid.
 *
 * WHY THE MODE IS A PARAMETER HERE TOO. D-S2-3 makes the scrambled-system control a generator mode
 * rather than a separate artifact, so the two arms are two bank files off one code path. The harness
 * takes the arm as an argument for the same reason: if the two arms were measured by different
 * drivers the contrast would be confounded with the driver. `--mode` selects which bank file of a
 * dual-mode pair is loaded; it changes nothing else about the simulation. The harness models NO
 * difference in child behaviour between arms — only children can supply that, which is Gate B.
 *
 * CLAIM BOUNDARY. Everything here is born-synthetic against `validated: false` banks. No output of
 * this script is evidence about a real child, and passing Gate A is not passing the gate (§4.1.2).
 *
 * Usage:
 *   pnpm exam:block-harness                          # calibration + Gate A on the reference bank
 *   pnpm exam:block-harness -- --calibrate           # E-095 reproduction: grid vs an existing bank
 *   pnpm exam:block-harness -- --noise-sweep         # sensitivity to the handover-noise SD
 *   pnpm exam:block-harness -- --guessing-probe      # what the `guessing = 0` fit does to a static child
 *   pnpm exam:block-harness -- --fix-probe           # every candidate remedy, costed side by side
 *   pnpm exam:block-harness -- --gate-a --bank FLU-OPCHAIN-01
 *   pnpm exam:block-harness -- --gate-a --bank grid          # Gate A with no bank at all
 *   pnpm exam:block-harness -- --gate-a --bank <path/to/bank.jsonl> --mode perTrial
 *   pnpm exam:block-harness -- --gate-a --bank grid --seeds 20260730,11,22,33,44,55,66,77
 *
 * Flags: --children N  --length N  --lambda-mean X  --lambda-sd X  --standing-noise X
 *        --guessing X  --fit-guessing X  --target-guessing X  --seed N  --seeds a,b,c  --json
 *        --targeting level|level-plain|projecting|frozen
 *
 * `--guessing` is the SIMULATED CHILD's floor (the truth). `--fit-guessing` and `--target-guessing`
 * are what the estimator assumes, in the readout fit and inside `nextTargetTheta` respectively.
 * Keeping the three separate is the whole point: the defect is a disagreement between them.
 */
