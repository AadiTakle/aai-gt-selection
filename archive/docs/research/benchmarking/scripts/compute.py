"""Generate every computed number in the benchmarking report.

Writes LaTeX into ../generated/ :
  numbers.tex      \newcommand macros for inline figures
  tab_*.tex        tabular bodies

Run:  python3 compute.py
No third-party dependencies.  See statlib.py for the routines and selftest.py
for their validation against published reference values.
"""

