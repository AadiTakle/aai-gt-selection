def n_for_noninferiority(margin, r_auc, power=0.80, alpha=0.025):
    """Smallest n at which the lower bound on the AUC difference stays above
    -margin, given a true difference of AUC_DIFF."""
    need = norm_ppf_cache_a + norm_ppf_cache_b
    eff = AUC_DIFF + margin
    n = 20
    while n < 200000:
        se = S.se_paired_auc_diff(AUC_INSTR, AUC_COMP, n, POOL_BASE_RATE, r_auc)
        if se > 0 and eff / se >= need:
            return n
        n += 1
    return None


