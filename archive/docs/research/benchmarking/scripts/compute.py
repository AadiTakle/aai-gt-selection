OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "generated")
os.makedirs(OUT, exist_ok=True)

MACROS = []


def macro(name, value):
    MACROS.append((name, value))
    return value


def num(x, dp=2):
    return ("%." + str(dp) + "f") % x


def pct(x, dp=1):
    return ("%." + str(dp) + "f") % (100.0 * x) + r"\%"


def powfmt(x, dp=2):
    """Powers round to 1.00 well before they reach it; say so rather than
    printing a certainty the design does not have."""
    if x > 0.995:
        return r"$>0.99$"
    return ("%." + str(dp) + "f") % x


def write(fname, body):
    path = os.path.join(OUT, fname)
    with open(path, "w") as fh:
        fh.write("% GENERATED BY scripts/compute.py -- DO NOT EDIT BY HAND\n")
        fh.write(body)
    print("wrote", os.path.relpath(path))


