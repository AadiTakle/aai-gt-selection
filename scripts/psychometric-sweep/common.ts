/**
 * Shared plumbing for the psychometric sweep scripts
 * (`docs/PSYCHOMETRIC_SWEEP_2026-07-28.md`).
 *
 * WHY THIS EXISTS: the three sweeps administer items the production bank does not
 * contain (blocks of arbitrary length, difficulty targeted continuously at a
 * running estimate, item pools at other guessing floors), so they cannot reuse
 * `scripts/persona-sim/bank.ts`. They still drive the SAME persona generator, so
 * the responses are produced by the same measurement models the recorded baseline
 * used — only the administration schedule differs.
 *
 * The recorded baseline in `docs/PERSONA_SIM_RESULTS.md` must keep reproducing, so
 * nothing here is imported by `scripts/persona-sim/*` and nothing here perturbs a
 * persona's RNG substream: a persona's draws are keyed by
 * `(seed, personaId, order, itemId)`, so a sweep that uses its own seed suffix and
 * its own item ids is independent of the baseline stream by construction.
 *
 * Born-synthetic only: no network, no database, no real data (D-006, R9).
 */

