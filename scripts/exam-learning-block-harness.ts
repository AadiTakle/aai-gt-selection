// --- calibration: does the harness reproduce E-095? ---------------------------

interface CalibrationRow {
  pool: string;
  length: number;
  r: number;
  meanSe: number;
  attenuationRatio: number;
  attenuationSlope: number;
  publishedR: number;
  publishedSe: number;
  publishedAttenuation: number;
}

function calibrate(settings: Settings): { rows: CalibrationRow[]; verdict: string[] } {
  const pools: { label: string; items: BankItem[] }[] = [
    { label: 'ideal 0.5-point grid', items: gridPool(0.5, 12) },
    { label: `bank ${REFERENCE_BANK}`, items: loadBank(REFERENCE_BANK).items },
  ];

  const rows: CalibrationRow[] = [];
  for (const pool of pools) {
    for (const length of LENGTH_LADDER) {
      const result = runCohort(cohortOptionsFor(settings, pool.items, { length }));
      const row = recoveryRow(result);
      const published = E095[length];
      rows.push({
        pool: pool.label,
        length,
        r: row.r,
        meanSe: row.meanSe,
        attenuationRatio: row.attenuationRatio,
        attenuationSlope: row.attenuationSlope,
        publishedR: published.r,
        publishedSe: published.meanSe,
        publishedAttenuation: published.attenuation,
      });
    }
  }

  const verdict: string[] = [];
  for (const row of rows.filter((r) => r.length === 30)) {
    const dR = Math.abs(row.r - row.publishedR);
    const dSe = Math.abs(row.meanSe - row.publishedSe);
    const dAtt = Math.min(
      Math.abs(row.attenuationRatio - row.publishedAttenuation),
      Math.abs(row.attenuationSlope - row.publishedAttenuation),
    );
    const ok =
      dR <= E095_TOLERANCE.r && dSe <= E095_TOLERANCE.meanSe && dAtt <= E095_TOLERANCE.attenuation;
    verdict.push(
      `${ok ? 'MATCH' : 'DIVERGES'}  ${row.pool} at 30 trials: ` +
        `|Δr| ${f(dR)} (tol ${E095_TOLERANCE.r}), |ΔSE| ${f(dSe)} (tol ${E095_TOLERANCE.meanSe}), ` +
        `|Δattenuation| ${f(dAtt)} (tol ${E095_TOLERANCE.attenuation})`,
    );
  }
  return { rows, verdict };
}

