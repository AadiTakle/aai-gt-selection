const CLAIM_HEADER = [
  '> **CLAIM BOUNDARY — READ FIRST.** Every row here is born-synthetic',
  '> (`synthetic_only: true`, `validated: false`; D-006, R9). Personas were generated by',
  '> the 3PL in `packages/cat-engine/src/irt.ts` and then scored by the estimator that',
  '> inverts that same 3PL, so **theta recovery here is CIRCULAR**. These numbers',
  '> demonstrate (a) that the session/scoring/estimation path is wired correctly,',
  "> (b) the estimator's bias and precision under known truth, and (c) how many items a",
  '> target SE requires. They are **not** evidence that any metric measures real ability,',
  '> **not** convergent or predictive validity, and **not** program impact — access,',
  '> reliability, outcome change, and causal impact are separate milestones (R10).',
  "> Tuning anything on this data tunes to the simulator's assumptions, not to children.",
].join('\n');

function mdTable(headers: readonly string[], rows: readonly (readonly string[])[]): string {
  return [
    `| ${headers.join(' | ')} |`,
    `|${headers.map(() => '---').join('|')}|`,
    ...rows.map((r) => `| ${r.join(' | ')} |`),
  ].join('\n');
}

function classificationRow(label: string, c: ClassificationResult): string[] {
  return [
    label,
    String(c.n),
    fmt(c.accuracy),
    fmt(c.kappa),
    fmt(c.sensitivity),
    fmt(c.specificity),
    fmt(c.falseNegativeRate),
    `${c.falseNegative}`,
  ];
}

function main(): void {
  const options = parseArgs(process.argv.slice(2));
  const startedAt = new Date().toISOString();
  const cohort = samplePersonaCohort({ seed: options.seed, n: options.n });

  const byArm = new Map<ArmId, PersonaArmResult[]>();
  for (const arm of ARMS) {
    byArm.set(
      arm.id,
      cohort.map((persona) => runPersonaArm(persona, arm, options.seed)),
    );
  }

  const armSummaries = ARMS.map((arm) => {
    const results = byArm.get(arm.id)!;
    const truthComposite = results.map((r) => r.persona.thetaMean);
    const eapComposite = results.map((r) => r.compositeEap);
    const mleComposite = results.map((r) => r.compositeMle);
    const ungated = results.map((r) => r.compositeEapUngated);
    const oracle = results.map((r) => r.compositeEapOracle);
    const ses = results.map((r) => r.compositeSe);

    const perDomain = SCORED_DOMAINS.map((domain) => {
      const usable = results.filter((r) => r.domains.find((d) => d.domain === domain)?.eap != null);
      const truth = usable.map((r) => r.persona.theta[domain]);
      const eap = usable.map((r) => r.domains.find((d) => d.domain === domain)!.eap!);
      const mle = usable.map((r) => r.domains.find((d) => d.domain === domain)!.mle!);
      const domainSes = usable.map((r) => r.domains.find((d) => d.domain === domain)!.eapSe!);
      return {
        domain,
        meanItems: mean(usable.map((r) => r.domains.find((d) => d.domain === domain)!.itemsUsed)),
        eap: recoveryBlock(truth, eap, domainSes),
        mle: recoveryBlock(truth, mle, domainSes),
      };
    });

    const perArchetype = PERSONA_ARCHETYPES.map((archetype) => {
      const group = results.filter((r) => r.persona.archetype === archetype);
      const truth = group.map((r) => r.persona.thetaMean);
      return {
        archetype,
        description: archetypeDescription(archetype),
        n: group.length,
        eap: recoveryBlock(
          truth,
          group.map((r) => r.compositeEap),
          group.map((r) => r.compositeSe),
        ),
        eapUngated: recoveryBlock(
          truth,
          group.map((r) => r.compositeEapUngated),
          group.map((r) => r.compositeSe),
        ),
        eapOracle: recoveryBlock(
          truth,
          group.map((r) => r.compositeEapOracle),
          group.map((r) => r.compositeSeOracle),
        ),
        meanEffortValidRate: mean(group.map((r) => r.effortValidRate)),
      };
    });

    const classification = classify(truthComposite, eapComposite, options.cut);
    const classificationUngated = classify(truthComposite, ungated, options.cut);
    const classificationOracle = classify(truthComposite, oracle, options.cut);
    // Select the same SHARE of the cohort the truth cut selects, but threshold on the
    // estimate's own distribution — the operationally realistic comparison.
    const selectedShare = truthComposite.filter((t) => t >= options.cut).length / results.length;
    const classificationMatched = classify(
      truthComposite,
      eapComposite,
      options.cut,
      percentileOf(eapComposite, 100 * (1 - selectedShare)),
    );

    const curves = {
      pooled: seCurve(results, 'pooled'),
      ...Object.fromEntries(SCORED_DOMAINS.map((d) => [d, seCurve(results, d)])),
    } as Record<string, ReturnType<typeof seCurve>>;

    const lambdaTruth: number[] = [];
    const lambdaSlope: number[] = [];
    const lambdaResidualTruth: number[] = [];
    const lambdaResidualSlope: number[] = [];
    for (const r of results) {
      if (r.learningRateSlope != null) {
        lambdaTruth.push(r.persona.learningRate);
        lambdaSlope.push(r.learningRateSlope);
      }
      if (r.learningRateResidualSlope != null) {
        lambdaResidualTruth.push(r.persona.learningRate);
        lambdaResidualSlope.push(r.learningRateResidualSlope);
      }
    }

    return {
      arm: arm.id,
      label: arm.label,
      meanItemsPresented: mean(results.map((r) => r.itemsPresented)),
      scoringMismatches: results.reduce((s, r) => s + r.scoringMismatches, 0),
      composite: {
        eap: recoveryBlock(truthComposite, eapComposite, ses),
        mle: recoveryBlock(truthComposite, mleComposite, ses),
        eapUngated: recoveryBlock(truthComposite, ungated, ses),
        eapOracle: recoveryBlock(
          truthComposite,
          oracle,
          results.map((r) => r.compositeSeOracle),
        ),
      },
      perDomain,
      perArchetype,
      classification,
      classificationUngated,
      classificationOracle,
      classificationMatched,
      engagement: {
        meanEffortValidRate: mean(results.map((r) => r.effortValidRate)),
        meanDetectedRapidGuesses: mean(results.map((r) => r.detectedRapidGuesses)),
        personasBelowGate: results.filter((r) => r.effortValidRate < 0.8).length,
      },
      learningRate: {
        n: lambdaTruth.length,
        pearson: pearson(lambdaTruth, lambdaSlope),
        spearman: spearman(lambdaTruth, lambdaSlope),
        meanSlope: mean(lambdaSlope),
        sdSlope: sd(lambdaSlope),
        residualN: lambdaResidualTruth.length,
        residualPearson: pearson(lambdaResidualTruth, lambdaResidualSlope),
        residualSpearman: spearman(lambdaResidualTruth, lambdaResidualSlope),
        residualMeanSlope: mean(lambdaResidualSlope),
      },
      seCurves: curves,
      itemsForTargetSe: Object.fromEntries(
        Object.entries(curves).map(([scope, curve]) => [
          scope,
          Object.fromEntries(
            options.targetSes.map((target) => [
              target,
              itemsForTargetSe(curve, target, results.length),
            ]),
          ),
        ]),
      ),
    };
  });

  // Decision consistency BETWEEN the two structures at the same cut: how often the
  // two sequencers put the same child on the same side of the band.
  const fixedResults = byArm.get('fixed')!;
  const twoStageResults = byArm.get('two-stage')!;
  const crossArm = agreement(
    fixedResults.map((r) => r.compositeEap >= options.cut),
    twoStageResults.map((r) => r.compositeEap >= options.cut),
  );

  mkdirSync(options.outDir, { recursive: true });

  const report = {
    claimBoundary:
      'Born-synthetic recovery study. Recovering theta from the generative model that produced ' +
      'the responses is circular: it evidences code correctness, estimator bias/precision, and ' +
      'item-count requirements only. Not real validity; not program impact (R10).',
    syntheticOnly: true as const,
    validated: false as const,
    startedAt,
    options: { ...options, targetSes: options.targetSes },
    bank: {
      items: bank.items.length,
      standingItems: bank.standingItemIdsInBankOrder.length,
      rapidGuessThresholdMs: bank.rapidGuessThresholdMs,
    },
    cohort: {
      n: cohort.length,
      byArchetype: Object.fromEntries(
        PERSONA_ARCHETYPES.map((a) => [a, cohort.filter((p) => p.archetype === a).length]),
      ),
      trueThetaMean: round(mean(cohort.map((p) => p.thetaMean)), 4),
      trueThetaSd: round(sd(cohort.map((p) => p.thetaMean)), 4),
    },
    arms: armSummaries,
    crossArmDecisionConsistency: crossArm,
  };

  const jsonPath = path.join(options.outDir, 'persona-recovery.json');
  writeFileSync(jsonPath, `${JSON.stringify(report, null, 2)}\n`);

  // --- markdown report -------------------------------------------------------
  const lines: string[] = [];
  lines.push('# Persona-Simulator Theta-Recovery Report (SYNTHETIC)', '');
  lines.push(CLAIM_HEADER, '');
  lines.push(
    `Run: N=${cohort.length} personas · seed \`${options.seed}\` · bank ${bank.items.length} items ` +
      `(${bank.standingItemIdsInBankOrder.length} standing) · cut theta >= ${options.cut} · ${startedAt}`,
    '',
  );
  lines.push(
    `Cohort true theta (mean of 4 domains): mean ${fmt(mean(cohort.map((p) => p.thetaMean)))}, ` +
      `SD ${fmt(sd(cohort.map((p) => p.thetaMean)))}.`,
    '',
  );

  for (const summary of armSummaries) {
    lines.push(`## Arm: ${summary.label}`, '');
    lines.push(
      `Mean items presented per persona: ${fmt(summary.meanItemsPresented, 1)}. ` +
        `Production-scoring vs generator mismatches: **${summary.scoringMismatches}** ` +
        '(any non-zero value means the keyed scoring path disagrees with the simulated response).',
      '',
    );
    const compositeRow = (label: string, block: RecoveryBlock, showSe: boolean): string[] => [
      label,
      String(block.n),
      fmt(block.rmse),
      fmt(block.bias),
      fmt(block.pearson),
      fmt(block.spearman),
      showSe ? fmt(block.meanSe) : '—',
    ];
    lines.push('### Composite theta recovery (all standing items pooled)', '');
    lines.push(
      mdTable(
        ['condition', 'n', 'RMSE', 'bias', 'Pearson r', 'Spearman rho', 'mean SE'],
        [
          compositeRow('EAP · RT gate (production path)', summary.composite.eap, true),
          compositeRow('MLE · RT gate', summary.composite.mle, false),
          compositeRow('EAP · no gate', summary.composite.eapUngated, false),
          compositeRow('EAP · perfect engagement telemetry', summary.composite.eapOracle, true),
        ],
      ),
      '',
    );
    lines.push(
      'The three gate conditions separate two different things. `no gate` -> `RT gate` is what the ' +
        'production rapid-guess filter buys. `RT gate` -> `perfect engagement telemetry` is what the ' +
        'RT filter CANNOT buy: it only catches FAST disengagement, so a slow checked-out response ' +
        "still enters theta at the guessing floor. The last row is therefore the estimator's own " +
        'bias/precision under known truth, with disengagement removed by construction.',
      '',
    );
    lines.push('### Per-domain recovery (EAP)', '');
    lines.push(
      mdTable(
        ['domain', 'mean items', 'n', 'RMSE', 'bias', 'Pearson r', 'mean SE', 'MLE RMSE'],
        summary.perDomain.map((d) => [
          d.domain,
          fmt(d.meanItems, 1),
          String(d.eap.n),
          fmt(d.eap.rmse),
          fmt(d.eap.bias),
          fmt(d.eap.pearson),
          fmt(d.eap.meanSe),
          fmt(d.mle.rmse),
        ]),
      ),
      '',
    );
    lines.push('### Per-archetype composite recovery (EAP)', '');
    lines.push(
      mdTable(
        [
          'archetype',
          'n',
          'RMSE',
          'bias',
          'Pearson r',
          'RMSE no gate',
          'RMSE perfect telemetry',
          'mean effort-valid rate',
        ],
        summary.perArchetype.map((a) => [
          a.archetype,
          String(a.n),
          fmt(a.eap.rmse),
          fmt(a.eap.bias),
          fmt(a.eap.pearson),
          fmt(a.eapUngated.rmse),
          fmt(a.eapOracle.rmse),
          fmt(a.meanEffortValidRate),
        ]),
      ),
      '',
    );
    lines.push(
      `### Classification at theta >= ${options.cut} (screening band, NOT an admission decision)`,
      '',
    );
    lines.push(
      mdTable(
        [
          'condition',
          'n',
          'accuracy',
          'kappa',
          'sensitivity',
          'specificity',
          'false-negative rate',
          'FN count',
        ],
        [
          classificationRow('EAP · RT gate (production path)', summary.classification),
          classificationRow('EAP · no gate', summary.classificationUngated),
          classificationRow('EAP · perfect engagement telemetry', summary.classificationOracle),
          classificationRow(
            `EAP · RT gate, cut matched on the estimate (${fmt(summary.classificationMatched.estimateCut, 3)})`,
            summary.classificationMatched,
          ),
        ],
      ),
      '',
    );
    lines.push(
      'EAP shrinks toward the prior, so applying the TRUE-theta threshold directly to theta-hat ' +
        'under-selects and inflates false negatives. The last row keeps the same selected share but ' +
        'thresholds on the estimate distribution; the gap between the two rows is a policy artefact ' +
        'of how a cut is defined, not a measurement result. Either way this is a screening band, ' +
        'never an admission decision (R10).',
      '',
    );
    lines.push('### Engagement gate', '');
    lines.push(
      `Mean effort-valid rate ${fmt(summary.engagement.meanEffortValidRate)}; ` +
        `mean detected rapid guesses per persona ${fmt(summary.engagement.meanDetectedRapidGuesses, 2)}; ` +
        `personas below a 0.8 effort-valid floor: ${summary.engagement.personasBelowGate}.`,
      '',
    );
    lines.push('### SE vs number of administered items (pooled across domains)', '');
    lines.push(
      mdTable(
        ['administered items', 'personas', 'mean SE', 'RMSE', 'bias'],
        summary.seCurves
          .pooled!.filter((p) => p.items <= 8 || p.items % 4 === 0)
          .map((p) => [
            String(p.items),
            String(p.personas),
            fmt(p.meanSe),
            fmt(p.rmse),
            fmt(p.bias),
          ]),
      ),
      '',
    );
    lines.push(
      'Administered items needed to reach a target mean SE (points backed by fewer than 90% of the ' +
        'cohort are ignored):',
      '',
    );
    lines.push(
      mdTable(
        ['scope', ...options.targetSes.map((t) => `SE<=${t}`), 'best mean SE (at k items)'],
        Object.entries(summary.itemsForTargetSe).map(([scope, targets]) => {
          const curve = summary.seCurves[scope] ?? [];
          const usable = curve.filter((p) => p.personas >= 0.9 * cohort.length);
          const best = usable.length ? usable[usable.length - 1]! : null;
          return [
            scope,
            ...options.targetSes.map((t) => {
              const value = (targets as Record<string, number | null>)[String(t)];
              return value == null ? 'not reached' : String(value);
            }),
            best ? `${fmt(best.meanSe)} (k=${best.items})` : 'n/a',
          ];
        }),
      ),
      '',
    );
    lines.push('### Learning-rate channel (STRETCH — hypothesis only, H-series)', '');
    lines.push(
      mdTable(
        ['lambda estimator', 'n', 'Pearson r', 'Spearman rho', 'mean slope'],
        [
          [
            'raw OLS score slope over the novel block',
            String(summary.learningRate.n),
            fmt(summary.learningRate.pearson),
            fmt(summary.learningRate.spearman),
            fmt(summary.learningRate.meanSlope, 4),
          ],
          [
            'slope of the 3PL residual (difficulty removed)',
            String(summary.learningRate.residualN),
            fmt(summary.learningRate.residualPearson),
            fmt(summary.learningRate.residualSpearman),
            fmt(summary.learningRate.residualMeanSlope, 4),
          ],
        ],
      ),
      '',
    );
    lines.push(
      'Read this as a NULL, and specifically as a POWER null. Two things are visible. (1) The block ' +
        'is administered at ASCENDING difficulty, so the raw score slope conflates the learning climb ' +
        'with difficulty escalation — that is what the negative mean raw slope is; residualizing ' +
        'against the 3PL expectation flips the mean slope positive, which is the climb. (2) Removing ' +
        'the confound does NOT rescue the per-persona correlation, so the binding constraint is trial ' +
        'count, not the confound: a lambda of ~0.03 theta/trial over a block this short moves the ' +
        'expected score by only a few hundredths, against a per-persona slope SD an order of magnitude ' +
        'larger. A within-session learning rate is not recoverable from a block of this length at all. ' +
        'This is a statement about THIS block design under THESE assumptions — it is neither support ' +
        'for nor refutation of the learning-rate hypothesis, which stays a labelled hypothesis ' +
        '(H-series) and not a validated metric.',
      '',
    );
  }

  lines.push('## Cross-structure decision consistency', '');
  lines.push(
    `Fixed vs two-stage agreement on the same cut: ${fmt(crossArm.agreement)} ` +
      `(kappa ${fmt(crossArm.kappa)}, n=${crossArm.n}). Disagreement is a precision consequence of ` +
      'the shorter two-stage form, not evidence that either structure is more valid.',
    '',
  );

  const mdPath = path.join(options.outDir, 'persona-recovery.md');
  writeFileSync(mdPath, `${lines.join('\n')}\n`);

  console.log(`report (json): ${jsonPath}`);
  console.log(`report (md):   ${mdPath}`);

  // --- harness dataset -------------------------------------------------------
  if (!options.runHarness) {
    console.log('');
    console.log(lines.join('\n'));
    return;
  }
  const dataset = buildHarnessDataset(fixedResults, options.seed);
  const written = writeHarnessDataset({
    outDir: options.outDir,
    name: 'persona_sim_scores',
    dataset,
    seed: options.seed,
    generationConfig: {
      n_personas: cohort.length,
      bank_items: bank.items.length,
      standing_items: bank.standingItemIdsInBankOrder.length,
      arm: 'fixed',
      rapid_guess_threshold_ms: bank.rapidGuessThresholdMs,
      response_model: '3PL (packages/cat-engine/src/irt.ts) driven by persona latent theta',
    },
    groundTruth: {
      model: 'correlated multivariate-normal latent traits -> 3PL responses',
      latent_traits:
        'per-domain theta, learning rate, speed, consistency, engagement, planfulness, creativity, working memory',
      dial_to_theta: 'theta = (dial - 10.5) / 3',
      archetype_counts: Object.fromEntries(
        PERSONA_ARCHETYPES.map((a) => [a, cohort.filter((p) => p.archetype === a).length]),
      ),
      notes:
        'true_theta_mean / true_learning_rate columns are the injected truth, retained for audit. ' +
        'Recovery against them is circular by construction.',
    },
    extraManifest: {
      claim_boundary:
        'cogat_sas and map_rit are SYNTHETIC PROXIES generated from the same latent theta as the ' +
        'item responses. They are circular with newtest_total and are NOT convergent-validity ' +
        'evidence. criterion_eoy is a synthetic criterion; incremental-validity output over it ' +
        'demonstrates the method only.',
    },
  });

  console.log(
    `harness csv:   ${written.csvPath} (${written.rows} rows, sha256 ${written.sha256.slice(0, 12)}...)`,
  );
  console.log('');
  console.log(lines.join('\n'));
}

