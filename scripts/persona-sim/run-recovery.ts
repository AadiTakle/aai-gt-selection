/**
 * Persona -> real session -> theta recovery runner
 * (`PERSONA_SIM_AND_VALIDATION_DESIGN.md` §1, "smallest vertical slice").
 *
 * WHAT THIS CAN AND CANNOT SHOW. It samples personas with KNOWN latent ability,
 * runs each through the production session shell and the production scoring rule,
 * recovers theta with the production estimator, and compares. Because the
 * responses were generated by the SAME 3PL the estimator inverts, the recovery is
 * CIRCULAR: a good RMSE demonstrates that the code path is wired correctly and
 * quantifies estimator bias/precision and the item count a target SE needs. It is
 * NOT evidence that any metric measures real ability, NOT convergent validity, and
 * NOT program impact — those are separate milestones needing external criteria and
 * a counterfactual design (R10).
 *
 * Everything is born-synthetic: no network, no database, no real data (D-006, R9).
 */

interface Options {
  n: number;
  seed: string;
  outDir: string;
  /** Absolute theta cut for the classification analysis. */
  cut: number;
  targetSes: number[];
  runHarness: boolean;
}

function parseArgs(argv: readonly string[]): Options {
  const get = (flag: string): string | undefined => {
    const i = argv.indexOf(flag);
    return i >= 0 ? argv[i + 1] : undefined;
  };
  return {
    n: Number(get('--n') ?? 1000),
    seed: get('--seed') ?? 'persona-sim-2026-07-27',
    outDir: get('--out') ?? path.join(process.cwd(), 'scripts/persona-sim/out'),
    // 1.2816 = the 90th percentile of N(0,1): a screening band, never an admission
    // decision (R10). GT owns the real cut as versioned policy (D-016).
    cut: Number(get('--cut') ?? 1.2816),
    targetSes: (get('--target-se') ?? '0.5,0.45,0.4,0.35,0.3,0.25').split(',').map(Number),
    runHarness: !argv.includes('--no-harness'),
  };
}

type ArmId = 'fixed' | 'two-stage';

interface ArmSpec {
  id: ArmId;
  label: string;
  makeSequencer: () => Sequencer;
}

const ARMS: ArmSpec[] = [
  {
    id: 'fixed',
    label: 'FixedSequencer (all items, domain-balanced)',
    makeSequencer: () => new FixedSequencer(),
  },
  {
    id: 'two-stage',
    label: 'TwoStageSequencer (bracketed standing -> effort placement)',
    makeSequencer: () => new TwoStageSequencer({ phase1CapPerDomain: 8, phase2PerDomain: 4 }),
  },
];

interface DomainRecovery {
  domain: ScoredDomain;
  itemsUsed: number;
  eap: number | null;
  eapSe: number | null;
  mle: number | null;
  mleSe: number | null;
}

interface PersonaArmResult {
  persona: Persona;
  arm: ArmId;
  itemsPresented: number;
  trials: PersonaTrial[];
  /** Mismatches between the production scoring rule and the generator's truth. */
  scoringMismatches: number;
  domains: DomainRecovery[];
  /** Composite EAP over standing trials that pass the RT-based gate (pooled). */
  compositeEap: number;
  compositeSe: number;
  compositeMle: number;
  /** Composite EAP with NO gating at all, for the gate's incremental effect. */
  compositeEapUngated: number;
  /**
   * Composite EAP over trials the GENERATOR marked on-task. The RT filter can only
   * catch FAST disengagement, so this is the "if engagement telemetry were perfect"
   * upper bound and isolates estimator bias from gate leakage.
   */
  compositeEapOracle: number;
  compositeSeOracle: number;
  effortValidRate: number;
  detectedRapidGuesses: number;
  /** OLS score slope inside the novel (effort) block, averaged over domains. */
  learningRateSlope: number | null;
  /**
   * The same slope after subtracting each item's expected score at the recovered
   * theta. The effort block is administered at ASCENDING difficulty, so a raw score
   * slope mixes the learning climb with difficulty escalation; residualizing on the
   * 3PL expectation removes the escalation and leaves the climb.
   */
  learningRateResidualSlope: number | null;
}

const bank = syntheticRecoveryBank();
const irtFor = (itemId: string) => bank.irtByItemId.get(itemId);

function toScoredResponses(trials: readonly PersonaTrial[]): ScoredResponse[] {
  return trials.map((t) => ({ irt: t.irt, correct: t.correct }));
}

/** The production gate: a response at or below the item RT floor is not evidence. */
function isEffortfulByGate(trial: PersonaTrial): boolean {
  return !isRapidGuess(trial.rtMs, bank.rapidGuessThresholdMs);
}

function runPersonaArm(persona: Persona, arm: ArmSpec, seed: string): PersonaArmResult {
  const run = createPersonaRun(persona, `${seed}|${arm.id}`, {
    itemIrt: (item) => irtFor(item.itemId),
  });
  const session = driveSession(bank.items, arm.makeSequencer(), run.respond);

  // The production path resolved correctness from the raw option index against the
  // bank key. If it disagrees with what the generator drew, the scoring path is
  // wrong — this is the one non-circular check in the whole runner.
  let scoringMismatches = 0;
  session.results.forEach((result, i) => {
    const trial = run.trials[i];
    if (!trial) {
      scoringMismatches += 1;
      return;
    }
    const expected = trial.correct ? 1 : 0;
    if (result.accuracy !== expected) scoringMismatches += 1;
  });

  const standing = run.trials.filter((t) => t.stage === 'standing');
  const gated = standing.filter(isEffortfulByGate);

  const domains: DomainRecovery[] = SCORED_DOMAINS.map((domain) => {
    const trials = gated.filter((t) => t.domain === domain);
    if (trials.length === 0) {
      return { domain, itemsUsed: 0, eap: null, eapSe: null, mle: null, mleSe: null };
    }
    const responses = toScoredResponses(trials);
    const eap = estimateThetaEap(responses);
    const mle = estimateThetaMle(responses);
    return {
      domain,
      itemsUsed: trials.length,
      eap: eap.theta,
      eapSe: eap.se,
      mle: mle.theta,
      mleSe: mle.se,
    };
  });

  const pooledGated = estimateThetaEap(toScoredResponses(gated));
  const pooledUngated = estimateThetaEap(toScoredResponses(standing));
  const pooledMle = estimateThetaMle(toScoredResponses(gated));
  const pooledOracle = estimateThetaEap(toScoredResponses(standing.filter((t) => t.onTask)));

  const slopes: number[] = [];
  const residualSlopes: number[] = [];
  for (const domain of SCORED_DOMAINS) {
    const block = run.trials.filter((t) => t.stage === 'effort' && t.domain === domain);
    if (block.length < 3) continue;
    const order = block.map((t) => (t.novelBlockIndex ?? 0) + 1);
    const scores = block.map((t) => (t.correct ? 1 : 0));
    const slope = olsLearningRate(order, scores);
    if (slope != null) slopes.push(slope);
    const thetaHat = domains.find((d) => d.domain === domain)?.eap;
    if (thetaHat != null) {
      const residuals = block.map((t, i) => scores[i]! - probabilityCorrect(thetaHat, t.irt));
      const residualSlope = olsLearningRate(order, residuals);
      if (residualSlope != null) residualSlopes.push(residualSlope);
    }
  }

  return {
    persona,
    arm: arm.id,
    itemsPresented: run.trials.length,
    trials: run.trials,
    scoringMismatches,
    domains,
    compositeEap: pooledGated.theta,
    compositeSe: pooledGated.se,
    compositeMle: pooledMle.theta,
    compositeEapUngated: pooledUngated.theta,
    compositeEapOracle: pooledOracle.theta,
    compositeSeOracle: pooledOracle.se,
    effortValidRate: standing.length === 0 ? Number.NaN : gated.length / standing.length,
    detectedRapidGuesses: standing.length - gated.length,
    learningRateSlope: slopes.length ? mean(slopes) : null,
    learningRateResidualSlope: residualSlopes.length ? mean(residualSlopes) : null,
  };
}

// --- aggregate recovery -------------------------------------------------------

interface RecoveryBlock {
  n: number;
  rmse: number;
  bias: number;
  pearson: number;
  spearman: number;
  meanSe: number;
}

function recoveryBlock(
  truth: readonly number[],
  estimate: readonly number[],
  ses: readonly number[],
): RecoveryBlock {
  return {
    n: truth.length,
    rmse: rmse(truth, estimate),
    bias: bias(truth, estimate),
    pearson: pearson(truth, estimate),
    spearman: spearman(truth, estimate),
    meanSe: mean(ses),
  };
}

/**
 * Mean posterior SE and RMSE after the first k ADMINISTERED standing items, per
 * domain and pooled. This is the design doc's key output: how many items a target
 * SE needs.
 *
 * The x-axis is ADMINISTERED items, not surviving items, and the estimate at k uses
 * whichever of the first k passed the gate. Indexing by surviving items instead
 * would censor the curve — personas who lose items to the gate would silently drop
 * out of the high-k rows and make the form look more precise than it is.
 */
function seCurve(results: readonly PersonaArmResult[], scope: ScoredDomain | 'pooled') {
  const perK = new Map<number, { se: number[]; err: number[] }>();
  for (const result of results) {
    const standing = result.trials.filter(
      (t) => t.stage === 'standing' && (scope === 'pooled' || t.domain === scope),
    );
    const truth = scope === 'pooled' ? result.persona.thetaMean : result.persona.theta[scope];
    for (let k = 1; k <= standing.length; k++) {
      const estimate = estimateThetaEap(
        toScoredResponses(standing.slice(0, k).filter(isEffortfulByGate)),
      );
      const bucket = perK.get(k) ?? { se: [], err: [] };
      bucket.se.push(estimate.se);
      bucket.err.push(estimate.theta - truth);
      perK.set(k, bucket);
    }
  }
  return [...perK.entries()]
    .sort((a, b) => a[0] - b[0])
    .map(([items, bucket]) => ({
      items,
      personas: bucket.se.length,
      meanSe: mean(bucket.se),
      rmse: Math.sqrt(mean(bucket.err.map((e) => e * e))),
      bias: mean(bucket.err),
    }));
}

/**
 * The smallest administered-item count whose MEAN posterior SE meets `target`.
 * Points backed by fewer than 90% of the cohort are ignored: a shorter form that
 * only some personas reached cannot be quoted as a form length.
 */
function itemsForTargetSe(
  curve: readonly { items: number; meanSe: number; personas: number }[],
  target: number,
  cohortSize: number,
): number | null {
  for (const point of curve) {
    if (point.personas < 0.9 * cohortSize) continue;
    if (point.meanSe <= target) return point.items;
  }
  return null;
}

// --- harness dataset ----------------------------------------------------------

function buildHarnessDataset(results: readonly PersonaArmResult[], seed: string) {
  const itemColumns = bank.standingItemIdsInBankOrder.map(
    (_, i) => `nt_${String(i + 1).padStart(2, '0')}`,
  );
  const columns = [
    'student_id',
    'grade',
    'cogat_sas',
    'map_rit',
    ...itemColumns,
    'newtest_total',
    'criterion_eoy',
    'subgroup_demo',
    'ell_status',
    'ses_band',
    'archetype',
    'true_theta_mean',
    'theta_hat_eap',
    'true_learning_rate',
  ];
  const columnByItemId = new Map(
    bank.standingItemIdsInBankOrder.map((id, i) => [id, itemColumns[i]!]),
  );

  const rows = results.map((result, index) => {
    const persona = result.persona;
    const rand = mulberry32(hashSeed(`${seed}|covariates|${persona.personaId}`));
    const normal = () => {
      let u = 0;
      let v = 0;
      let s = 0;
      do {
        u = 2 * rand() - 1;
        v = 2 * rand() - 1;
        s = u * u + v * v;
      } while (s === 0 || s >= 1);
      return u * Math.sqrt((-2 * Math.log(s)) / s);
    };

    const grade = 3 + Math.floor(rand() * 6);
    const theta = persona.thetaMean;
    // SYNTHETIC PROXIES for the harness's column contract, generated from the same
    // latent theta -> circular with the new test by construction. NOT CogAT/MAP.
    const cogat = Math.round(
      Math.min(160, Math.max(55, 100 + 16 * (0.9 * theta + 0.44 * normal()))),
    );
    const mapRit = Math.round(
      Math.min(300, Math.max(120, 190 + (grade - 3) * 5 + 15 * (0.82 * theta + 0.4 * normal()))),
    );
    const lambdaZ = (persona.learningRate - 0.03) / 0.03;
    const criterion =
      Math.round((50 + 10 * (0.55 * theta + 0.3 * lambdaZ + 0.55 * normal())) * 100) / 100;

    const row: Record<string, CsvValue> = {
      student_id: `PERSONA-SYN-${String(index + 1).padStart(6, '0')}`,
      grade,
      cogat_sas: cogat,
      map_rit: mapRit,
      newtest_total: 0,
      criterion_eoy: criterion,
      subgroup_demo: rand() < 0.45 ? 'focal' : 'reference',
      ell_status: rand() < 0.22 ? 'ELL' : 'non-ELL',
      ses_band: rand() < 0.4 ? 'lower-income' : 'higher-income',
      archetype: persona.archetype,
      true_theta_mean: round(theta, 4),
      theta_hat_eap: round(result.compositeEap, 4),
      true_learning_rate: round(persona.learningRate, 5),
    };
    for (const column of itemColumns) row[column] = 0;
    let total = 0;
    for (const trial of result.trials) {
      const column = columnByItemId.get(trial.itemId);
      if (!column) continue;
      const scored = trial.correct ? 1 : 0;
      row[column] = scored;
      total += scored;
    }
    row.newtest_total = total;
    return row;
  });

  return { columns, rows };
}

